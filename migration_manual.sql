-- 6. Registrar migration no histórico do EF Core
INSERT INTO "__EFMigrationsHistory" ("MigrationId", "ProductVersion")
SELECT '20260613000001_InitialCreate', '8.0.10'
FROM DUAL
WHERE NOT EXISTS (
  SELECT 1 FROM "__EFMigrationsHistory"
  WHERE "MigrationId" = '20260613000001_InitialCreate'
);
COMMIT;

-- 7. Verificar tabelas criadas
