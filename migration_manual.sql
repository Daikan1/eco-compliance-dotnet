-- 1. Tabela de controle de migrations do EF Core
DECLARE v NUMBER; BEGIN
  SELECT COUNT(*) INTO v FROM user_tables WHERE table_name='__EFMigrationsHistory';
  IF v=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE "__EFMigrationsHistory" (
      "MigrationId"    NVARCHAR2(150) NOT NULL,
      "ProductVersion" NVARCHAR2(32)  NOT NULL,
      CONSTRAINT "PK___EFMigrationsHistory" PRIMARY KEY ("MigrationId")
    )';
  END IF;
END;
/

-- 2. COMPANY (pode já existir do projeto Java)
DECLARE v NUMBER; BEGIN
  SELECT COUNT(*) INTO v FROM user_tables WHERE table_name='COMPANY';
  IF v=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE COMPANY (
      ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      NAME   VARCHAR2(255) NOT NULL,
      CNPJ   VARCHAR2(20),
      SECTOR VARCHAR2(100)
    )';
  END IF;
END;
/

-- 3. COMPLIANCE_RECORDS (pode já existir do projeto Java)
DECLARE v NUMBER; BEGIN
  SELECT COUNT(*) INTO v FROM user_tables WHERE table_name='COMPLIANCE_RECORDS';
  IF v=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE COMPLIANCE_RECORDS (
      ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      COMPANY_ID      NUMBER NOT NULL,
      COMPLIANCE_TYPE VARCHAR2(255) NOT NULL,
      STATUS          VARCHAR2(100) NOT NULL,
      REPORT_DATE     DATE NOT NULL,
      CONSTRAINT FK_CR_COMPANY FOREIGN KEY (COMPANY_ID) REFERENCES COMPANY(ID)
    )';
  END IF;
END;
/

-- 4. ESG_INDICATORS (nova tabela — só existe no projeto .NET)
